const CRC32_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let i = 0; i < 256; i++) {
    let c = i;
    for (let k = 0; k < 8; k++) {
      c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    }
    table[i] = c >>> 0;
  }
  return table;
})();

function crc32(buf: Buffer): number {
  let crc = 0xffffffff;
  for (let i = 0; i < buf.length; i++) {
    crc = CRC32_TABLE[(crc ^ buf[i]) & 0xff] ^ (crc >>> 8);
  }
  return (crc ^ 0xffffffff) >>> 0;
}

/**
 * Минимальный генератор валидного ZIP/JAR архива без зависимостей от Node 22+ zlib.crc32.
 * Корректно работает на Node 18/20/22+ и в Vercel Serverless.
 */
function buildPlaceholderJar(entries: Array<{ name: string; content: string }>): Buffer {
  const localParts: Buffer[] = [];
  const centralParts: Buffer[] = [];
  let offset = 0;

  for (const entry of entries) {
    const nameBuf = Buffer.from(entry.name, 'utf8');
    const dataBuf = Buffer.from(entry.content, 'utf8');
    const crc = crc32(dataBuf);

    // Local file header (30 bytes + filename)
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0, 6);
    local.writeUInt16LE(0, 8); // compression: store
    local.writeUInt16LE(0, 10);
    local.writeUInt16LE(0, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(dataBuf.length, 18);
    local.writeUInt32LE(dataBuf.length, 22);
    local.writeUInt16LE(nameBuf.length, 26);
    local.writeUInt16LE(0, 28);

    localParts.push(local, nameBuf, dataBuf);

    // Central directory header (46 bytes + filename)
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0, 8);
    central.writeUInt16LE(0, 10);
    central.writeUInt16LE(0, 12);
    central.writeUInt16LE(0, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(dataBuf.length, 20);
    central.writeUInt32LE(dataBuf.length, 24);
    central.writeUInt16LE(nameBuf.length, 28);
    central.writeUInt16LE(0, 30);
    central.writeUInt16LE(0, 32);
    central.writeUInt16LE(0, 34);
    central.writeUInt16LE(0, 36);
    central.writeUInt32LE(0, 38);
    central.writeUInt32LE(offset, 42);

    centralParts.push(central, nameBuf);
    offset += local.length + nameBuf.length + dataBuf.length;
  }

  const centralDir = Buffer.concat(centralParts);
  const endRecord = Buffer.alloc(22);
  endRecord.writeUInt32LE(0x06054b50, 0);
  endRecord.writeUInt16LE(0, 4);
  endRecord.writeUInt16LE(0, 6);
  endRecord.writeUInt16LE(entries.length, 8);
  endRecord.writeUInt16LE(entries.length, 10);
  endRecord.writeUInt32LE(centralDir.length, 12);
  endRecord.writeUInt32LE(offset, 16);
  endRecord.writeUInt16LE(0, 20);

  return Buffer.concat([...localParts, centralDir, endRecord]);
}

export async function GET(
  _request: NextRequest,
  context: { params: Promise<{ tier: string }> },
) {
  const { tier } = await context.params;
  const settings = await db.getSiteSettings();

  if (tier === 'free') {
    const jarBuffer = buildPlaceholderJar([
      {
        name: 'META-INF/MANIFEST.MF',
        content: 'Manifest-Version: 1.0\nImplementation-Title: Wire DLC Free Edition (Stub)\n',
      },
      {
        name: 'fabric.mod.json',
        content: JSON.stringify(
          {
            schemaVersion: 1,
            id: 'wiredlc_free',
            version: '1.0.0-stub',
            name: 'Wire DLC (Free MVP Stub)',
            description: 'Placeholder archive generated by Wire DLC web platform.',
            environment: 'client',
            depends: {
              fabricloader: '>=0.16.0',
              minecraft: settings.minecraftVersion,
            },
          },
          null,
          2,
        ),
      },
      {
        name: 'README_WIRE_DLC.txt',
        content: [
          'Wire DLC — Бесплатная сборка (MVP Заглушка)',
          `Версия Minecraft: ${settings.minecraftVersion} (${settings.loaderName})`,
          '',
          'Этот файл является безопасной заглушкой для тестирования скачивания на сайте.',
          'Замените маршрут /api/download/[tier] на реальный CDN/S3/Supabase Storage URL перед запуском в прод.',
        ].join('\n'),
      },
    ]);

    return new NextResponse(new Uint8Array(jarBuffer), {
      status: 200,
      headers: {
        'Content-Type': 'application/java-archive',
        'Content-Disposition': `attachment; filename="wiredlc-free-${settings.minecraftVersion}-fabric.jar"`,
        'Cache-Control': 'no-store',
      },
    });
  }

  if (tier === 'premium') {
    const session = await getServerSession();
    if (!session) {
      return NextResponse.json({ error: 'Требуется авторизация' }, { status: 401 });
    }
    const user = await db.findUserById(session.sub);
    if (!user) {
      return NextResponse.json({ error: 'Пользователь не найден' }, { status: 404 });
    }

    const isPaidActive =
      user.subscriptionTier === 'lifetime' ||
      (user.subscriptionTier !== 'free' &&
        (!user.subscriptionExpiresAt ||
          new Date(user.subscriptionExpiresAt).getTime() > Date.now()));

    if (!isPaidActive) {
      return NextResponse.json(
        { error: 'Для скачивания полной версии требуется активная подписка' },
        { status: 403 },
      );
    }

    const jarBuffer = buildPlaceholderJar([
      {
        name: 'META-INF/MANIFEST.MF',
        content: 'Manifest-Version: 1.0\nImplementation-Title: Wire DLC Full Loader (Stub)\n',
      },
      {
        name: 'wiredlc-license.json',
        content: JSON.stringify(
          {
            username: user.username,
            tier: user.subscriptionTier,
            hwid: user.hwid || 'UNBOUND',
            minecraft: settings.minecraftVersion,
            loader: settings.loaderName,
          },
          null,
          2,
        ),
      },
      {
        name: 'README_WIRE_DLC.txt',
        content: `Wire DLC Full Edition (Stub) — Аккаунт: ${user.username} (${user.subscriptionTier})`,
      },
    ]);

    return new NextResponse(new Uint8Array(jarBuffer), {
      status: 200,
      headers: {
        'Content-Type': 'application/java-archive',
        'Content-Disposition': `attachment; filename="wiredlc-loader-${settings.minecraftVersion}-fabric.jar"`,
        'Cache-Control': 'no-store',
      },
    });
  }

  return NextResponse.json({ error: 'Неизвестный тип сборки' }, { status: 404 });
}
